package ui;

public class MenuPrinter {
    /**
     * Выводит справку по командам.
     */
    public static void printHelp() {
        System.out.println("""

            ╔══════════════════════════════════════════════════════╗
            ║                    СПРАВКА                           ║
            ╚══════════════════════════════════════════════════════╝

            📌 РЕЖИМЫ РАБОТЫ:

              1. Интерактивный — выбирайте пункты меню цифрами
              2. Командный — вводите команду целиком с флагами

            📌 ДОСТУПНЫЕ КОМАНДЫ:

              help              Показать эту справку
              exit              Выйти из программы
              clear             Очистить текущие настройки
              start [флаги]     Запустить сортировку

            📌 ФЛАГИ ДЛЯ КОМАНДЫ start:

              -c, --class    <1-5>      Класс для сортировки
              -s, --source   <1-3>      Источник данных
              -n, --size     <1-10000>  Размер коллекции
              -f, --field    <1-3>      Поле для сортировки
              -a, --algo     <1-3>      Алгоритм сортировки
              -p, --path     <путь>     Путь к файлу (для source=3)

            📌 КЛАССЫ (-c):
              1 - Автомобиль (Мощность, Модель, Год)
              2 - Автобус (Номер, Модель, Пробег)
              3 - Пользователь (Имя, Пароль, Почта)
              4 - Студент (Группа, Средний балл, Зачетка)
              5 - Бочка (Объем, Материал хранения, Материал)

            📌 ИСТОЧНИКИ (-s):
              1 - Ручной ввод
              2 - Случайные данные
              3 - Из файла

            📌 АЛГОРИТМЫ (-a):
              1 - Bubble Sort
              2 - Quick Sort
              3 - Merge Sort

            📌 ПРИМЕРЫ:

              start -c 1 -s 2 -n 10 -f 1 -a 2
              ➜ Сортировка автомобилей по мощности (Quick Sort, 10 шт, рандом)

              start -c 4 -s 2 -n 50 -f 2 -a 3
              ➜ Сортировка студентов по среднему баллу (Merge Sort, 50 шт)

              start -c 2 -s 3 -p data.csv -n 20 -f 3 -a 1
              ➜ Сортировка автобусов из файла по пробегу (Bubble Sort)

              help
              ➜ Показать эту справку

            """);
    }

    /**
     * Выводит подсказку о доступности командного режима.
     */
    public static void printCommandHint() {
        System.out.println("💡 Подсказка: введите 'help' для справки по командам");
    }
}
